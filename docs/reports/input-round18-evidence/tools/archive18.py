def sha_bytes(data):
    return hashlib.sha256(data).hexdigest()


def sha(path):
    return sha_bytes(Path(path).read_bytes())


def git(*arguments):
    return subprocess.check_output(['git', *arguments], cwd=ROOT).decode('utf-8').strip()


def record(destination, content, source, raw=None):
    name = str(destination).replace('\\', '/')
    assert name not in planned, '重复归档目标：' + name
    item = {'bytes': len(content), 'sha256': sha_bytes(content), 'source': str(source)}
    if raw is not None:
        assert gzip.decompress(content) == raw
        item.update(raw_bytes=len(raw), raw_sha256=sha_bytes(raw), gzip_CRC_and_exact_bytes=True)
    planned[name] = item
    if not args.plan:
        target = OUT / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            assert target.read_bytes() == content, '已有归档内容不一致，保留并停止：' + str(target)
        else:
            target.write_bytes(content)


def add(path, destination, required=True):
    path = Path(path)
    if not path.is_file():
        if required:
            raise FileNotFoundError(path)
        missing_optional.append(str(path))
        return
    raw = path.read_bytes()
    if path.suffix == '.gz':
        unpacked = gzip.decompress(raw)
        record(destination, raw, path, unpacked)
    elif len(raw) > COMPRESS_ABOVE and path.suffix != '.zip':
        record(str(destination) + '.gz', gzip.compress(raw, mtime=0), path, raw)
    else:
        record(destination, raw, path)


def tree(directory, prefix, required=True, select=None):
    directory = Path(directory)
    if not directory.is_dir():
        if required:
            raise FileNotFoundError(directory)
        missing_optional.append(str(directory))
        return
    for path in sorted(directory.rglob('*')):
        if not path.is_file():
            continue
        relative = path.relative_to(directory)
        if EXCLUDED_PARTS.intersection(relative.parts) or path.suffix.lower() in EXCLUDED_SUFFIXES:
            continue
        if select is not None and not select(path):
            continue
        # 已有逐字节校验的gzip保留一份，避免重复收录几百MB原始日志。
        packed = path.with_name(path.name + '.gz')
        if path.suffix != '.gz' and packed.is_file():
            assert gzip.decompress(packed.read_bytes()) == path.read_bytes(), str(path)
            skipped_duplicate_raw.append(str(path))
            continue
        add(path, Path(prefix) / relative)


def generated(name, value):
    data = (json.dumps(value, ensure_ascii=False, indent=2) + '\n').encode('utf-8')
    record(name, data, 'generated by archive18.py')


