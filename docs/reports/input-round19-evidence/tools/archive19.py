def add(path,name,required=True):
    path=Path(path)
    if not path.is_file():
        if required:raise FileNotFoundError(path)
        missing.append(str(path));return
    raw=path.read_bytes()
    if path.suffix=='.gz':put(name,raw,path,gzip.decompress(raw))
    elif len(raw)>100000 and path.suffix!='.zip':put(str(name)+'.gz',gzip.compress(raw,mtime=0),path,raw)
    else:put(name,raw,path)
def tree(directory,prefix,required=True,select=None):
    directory=Path(directory)
    if not directory.is_dir():
        if required:raise FileNotFoundError(directory)
        missing.append(str(directory));return
    for folder,dirs,names in os.walk(directory):
        dirs[:]=sorted(d for d in dirs if d not in EXCLUDED_DIRS)
        for name in sorted(names):
            p=Path(folder)/name
            if p.is_symlink() or p.suffix.lower() in EXCLUDED_SUFFIXES:continue
            if select is not None and not select(p):continue
            packed=p.with_name(p.name+'.gz')
            if p.suffix!='.gz' and packed.is_file():
                assert gzip.decompress(packed.read_bytes())==p.read_bytes(),str(p)
                deduplicated.append(str(p));continue
            add(p,Path(prefix)/p.relative_to(directory))
